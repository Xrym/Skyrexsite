# Update local DB
with sqlite3.connect(LOCAL_DB) as conn:
    cur = conn.cursor()
    cur.execute("DELETE FROM ai_rules;")
    for idx, (title, text) in enumerate(UPDATED_RULES, 1):
        cur.execute("INSERT INTO ai_rules (id, title, rule_text, is_active, created_by) VALUES (?, ?, ?, 1, 'admin');", (idx, title, text))
    conn.commit()
print("1. Local DB updated successfully.")

# Update remote DB via SSH
client = paramiko.SSHClient()
client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
client.connect(HOST, username=USER, password=SSH_PASSWORD, timeout=10)

update_sql = "DELETE FROM ai_rules;\n"
for idx, (title, text) in enumerate(UPDATED_RULES, 1):
    safe_title = title.replace("'", "''")
    safe_text = text.replace("'", "''")
    update_sql += f"INSERT INTO ai_rules (id, title, rule_text, is_active, created_by) VALUES ({idx}, '{safe_title}', '{safe_text}', 1, 'admin');\n"

stdin, stdout, stderr = client.exec_command(f"sqlite3 /var/www/skyrex/catalog.db \"{update_sql}\"")
print("2. Remote DB updated successfully.")

# Restart skyrex
stdin, stdout, stderr = client.exec_command("systemctl restart skyrex")
print("3. Skyrex service restarted on remote server.")

client.close()
